package droidmap

fun formatFindings(findings: List<Finding>): String {
    if (findings.isEmpty()) return "No findings."
    val lines = ArrayList<String>()
    for (f in findings) {
        val loc = if (f.file != null && f.line != null) "${f.file}:${f.line}" else (f.file ?: "-")
        lines.add("${f.severity.padEnd(7)} ${f.rule.padEnd(28)} $loc\n        ${f.message}")
    }
    val counts = findings.groupingBy { it.severity }.eachCount()
    lines.add("")
    lines.add(listOf("error", "warning", "info").filter { (counts[it] ?: 0) > 0 }
        .joinToString(", ") { "${counts[it]} $it${if (counts[it] != 1) "s" else ""}" })
    return lines.joinToString("\n")
}

/** SARIF 2.1.0 for GitHub code scanning; [prefix] is put before every file path (see `check --sarif`). */
fun toSarif(findings: List<Finding>, prefix: String = ""): Map<String, Any?> {
    val level = mapOf("error" to "error", "warning" to "warning", "info" to "note")
    val rules = RULES.map { (id, v) ->
        linkedMapOf("id" to id, "shortDescription" to mapOf("text" to v.second),
            "defaultConfiguration" to mapOf("level" to (if (v.first == "off") "none" else level[v.first] ?: "none")))
    }
    val results = findings.map { f ->
        val r = linkedMapOf<String, Any?>("ruleId" to f.rule, "level" to (level[f.severity] ?: "note"), "message" to mapOf("text" to f.message))
        if (f.file != null) {
            val phys = linkedMapOf<String, Any?>("artifactLocation" to mapOf("uri" to prefix + f.file))
            if (f.line != null) phys["region"] = mapOf("startLine" to f.line)
            r["locations"] = listOf(mapOf("physicalLocation" to phys))
        }
        r
    }
    return linkedMapOf(
        "\$schema" to "https://json.schemastore.org/sarif-2.1.0.json", "version" to "2.1.0",
        "runs" to listOf(mapOf("tool" to mapOf("driver" to linkedMapOf("name" to "droidmap", "version" to VERSION, "rules" to rules)),
            "results" to results)),
    )
}

private fun md(s: String) = s.replace("|", "\\|").replace("\n", " ")

fun reportMarkdown(g: Graph, findings: List<Finding>, title: String): String {
    val out = arrayListOf("# droidmap report: $title", "", "Generated by droidmap $VERSION. Paths are relative to the project root.", "")
    val mods = g.byKind("module")
    val dbs = g.byKind("room_database")
    val dests = g.byKind("nav_destination").filter { it.attrs.bool("registered") }
    val providers = g.byKind("hilt_provider")
    val vms = g.byKind("viewmodel")
    val errors = findings.count { it.severity == "error" }
    val warnings = findings.count { it.severity == "warning" }
    out += listOf("## Summary", "",
        "- ${mods.size} Gradle modules, ${g.edgesOf("depends_on").size} module dependencies",
        "- ${dbs.size} Room database${if (dbs.size != 1) "s" else ""}, ${g.byKind("room_migration").size} migrations, " +
            "${g.byKind("room_schema").size} schema files",
        "- ${dests.size} navigation destinations, ${g.edgesOf("navigates_to").size} navigate calls resolved",
        "- ${providers.size} Hilt bindings (@Provides/@Binds), ${vms.size} ViewModels",
        "- Findings: $errors errors, $warnings warnings; ${g.unresolved.size} references not resolved", "")
    if (findings.isNotEmpty()) {
        out += listOf("## Findings", "", "| Severity | Rule | Where | Message |", "|---|---|---|---|")
        for (f in findings) {
            val loc = if (f.file != null && f.line != null) "${f.file}:${f.line}" else (f.file ?: "")
            out.add("| ${f.severity} | ${f.rule} | `$loc` | ${md(f.message)} |")
        }
        out.add("")
    }
    if (mods.isNotEmpty()) {
        out += listOf("## Modules", "", "| Module | Depends on (main) | Used by |", "|---|---|---|")
        for (m in mods.sortedBy { it.label }) {
            val deps = g.outEdges(m.id).filter { it.kind == "depends_on" && !it.attrs.bool("test") }.map { g.label(it.target) }.toSortedSet()
            val users = g.inEdges(m.id).filter { it.kind == "depends_on" }.map { g.label(it.source) }.toSortedSet()
            out.add("| `${m.label}` | ${deps.joinToString(", ").ifEmpty { "-" }} | ${users.joinToString(", ").ifEmpty { "-" }} |")
        }
        out.add("")
    }
    if (dbs.isNotEmpty()) {
        out += listOf("## Room", "")
        for (db in dbs) {
            val fq = db.id.substringAfter("::")
            val schemas = g.byKind("room_schema").filter { it.attrs.str("db") == fq }.mapNotNull { it.attrs.int("version") }.sorted()
            fun related(kind: String) = g.outEdges(db.id).filter { it.kind == kind }.map { g.label(it.target) }.sorted().joinToString(", ").ifEmpty { "-" }
            out += listOf("### ${db.label} (version ${db.attrs.int("version")})", "",
                "- File: `${db.file}:${db.line}`",
                "- Schema files: ${schemas.joinToString(", ").ifEmpty { "none" }}",
                "- Entities: ${related("contains_entity")}",
                "- DAOs: ${related("contains_dao")}",
                "", "| Step | Kind | Tested by |", "|---|---|---|")
            val migs = g.byKind("room_migration").filter { it.attrs.str("db") == fq }
                .sortedWith(compareBy({ it.attrs.int("from_version") }, { it.attrs.int("to_version") }))
            for (m in migs) {
                val tests = g.inEdges(m.id).filter { it.kind == "tests" }.map { g.label(it.source) }.sorted()
                out.add("| ${m.attrs.int("from_version")} -> ${m.attrs.int("to_version")} | ${m.attrs.str("style")} | " +
                    "${tests.joinToString(", ").ifEmpty { "**none**" }} |")
            }
            out.add("")
        }
    }
    if (dests.isNotEmpty()) {
        out += listOf("## Navigation", "", "| Destination | API | Shows | Reached from |", "|---|---|---|---|")
        for (d in dests.sortedBy { it.label }) {
            val shows = g.outEdges(d.id).filter { it.kind == "shows" }.map { g.label(it.target) }.sorted().joinToString(", ")
            val srcs = g.inEdges(d.id).filter { it.kind == "navigates_to" || it.kind == "starts_at" }.map { g.label(it.source) }.toSortedSet()
            out.add("| `${d.label}` | ${d.attrs.str("api")} | ${shows.ifEmpty { "-" }} | ${srcs.joinToString(", ").ifEmpty { "-" }} |")
        }
        out.add("")
    }
    if (providers.isNotEmpty() || vms.isNotEmpty()) {
        out += listOf("## Hilt", "")
        if (vms.isNotEmpty()) {
            out += listOf("| ViewModel | Injects |", "|---|---|")
            for (v in vms.sortedBy { it.label }) {
                val deps = g.outEdges(v.id).filter { it.kind == "injects" }.map { g.label(it.target) }.sorted()
                out.add("| ${v.label} | ${deps.joinToString(", ").ifEmpty { "-" }} |")
            }
            out.add("")
        }
        if (providers.isNotEmpty()) {
            out += listOf("| Binding | Provides | Module |", "|---|---|---|")
            for (pn in providers.sortedBy { it.label }) {
                val a = pn.attrs
                val q = a.str("qualifier")?.let { " @$it" } ?: ""
                out.add("| ${pn.label} (${a.str("style")}) | `${a.str("returns")}`$q | ${(a.str("hilt_module") ?: "-").substringAfterLast('.')} |")
            }
            out.add("")
        }
    }
    if (g.unresolved.isNotEmpty()) {
        out += listOf("## Not resolved", "", "Static analysis cannot follow these; check them by hand.", "")
        for ((kind, items) in g.unresolved.groupBy { it.kind }.toSortedMap()) {
            out.add("- **$kind** (${items.size}): " + items.take(8).joinToString("; ") { u ->
                "`${u.text.take(60)}` ${u.file ?: ""}${u.line?.let { ":$it" } ?: ""} (${u.reason})"
            } + if (items.size > 8) " ..." else "")
        }
        out.add("")
    }
    return out.joinToString("\n")
}
