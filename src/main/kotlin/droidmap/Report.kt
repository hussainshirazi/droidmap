package droidmap

/** Diagrams larger than this are left out: they would not be readable. */
private const val MAX_DIAGRAM_NODES = 80

private fun md(s: String) = s.replace("|", "\\|").replace("\n", " ")
private fun list(items: Collection<String>) = items.joinToString(", ").ifEmpty { "-" }

/** A Markdown overview of the project: what it has, the findings, and diagrams GitHub renders (Mermaid). */
fun reportMarkdown(g: Graph, findings: List<Finding>, title: String): String {
    val out = arrayListOf("# droidmap report: $title", "", "Generated by droidmap $VERSION. Paths are relative to the project root.", "")
    summary(g, findings, out)
    if (findings.isNotEmpty()) {
        out += listOf("## Findings", "", "| Severity | Rule | Where | Message |", "|---|---|---|---|")
        for (f in findings) out.add("| ${f.severity} | ${f.rule} | `${location(f.file, f.line)}` | ${md(f.message)} |")
        out.add("")
    }
    modules(g, out)
    room(g, out)
    navigation(g, out)
    di(g, out)
    permissions(g, out)
    if (g.unresolved.isNotEmpty()) {
        out += listOf("## Not resolved", "", "Static analysis cannot follow these; check them by hand.", "")
        for ((kind, items) in g.unresolved.groupBy { it.kind }.toSortedMap()) {
            out.add("- **$kind** (${items.size}): " + items.take(8).joinToString("; ") { u ->
                "`${u.text.take(60)}` ${location(u.file, u.line)} (${u.reason})"
            } + if (items.size > 8) " ..." else "")
        }
        out.add("")
    }
    return out.joinToString("\n")
}

private fun summary(g: Graph, findings: List<Finding>, out: MutableList<String>) {
    val dbs = g.byKind("room_database").size
    val errors = findings.count { it.severity == "error" }
    val warnings = findings.count { it.severity == "warning" }
    out += listOf("## Summary", "",
        "- ${g.byKind("module").size} Gradle modules, ${g.edgesOf("depends_on").size} module dependencies",
        "- $dbs Room ${plural(dbs, "database")}, ${g.byKind("room_migration").size} migrations, ${g.byKind("room_schema").size} schema files",
        "- ${g.byKind("nav_destination").count { it.attrs.bool("registered") }} navigation destinations, " +
            "${g.edgesOf("navigates_to").size} navigate calls resolved",
        "- ${g.byKind("hilt_provider").size} Hilt bindings (@Provides/@Binds), ${g.byKind("koin_definition").size} Koin definitions, " +
            "${g.byKind("viewmodel").size} ViewModels",
        "- Findings: $errors ${plural(errors, "error")}, $warnings ${plural(warnings, "warning")}; " +
            "${g.unresolved.size} references not resolved", "")
}

private fun modules(g: Graph, out: MutableList<String>) {
    val mods = g.byKind("module").sortedBy { it.label }
    if (mods.isEmpty()) return
    out += listOf("## Modules", "", "| Module | Depends on (main) | Used by |", "|---|---|---|")
    for (m in mods) {
        val deps = g.outEdges(m.id).filter { it.kind == "depends_on" && !it.attrs.bool("test") }.map { g.label(it.target) }.toSortedSet()
        val users = g.inEdges(m.id).filter { it.kind == "depends_on" }.map { g.label(it.source) }.toSortedSet()
        out.add("| `${m.label}` | ${list(deps)} | ${list(users)} |")
    }
    out.add("")
    val main = g.edgesOf("depends_on").filter { !it.attrs.bool("test") }
    if (main.isNotEmpty()) {
        out += listOf("Main dependencies (a dotted arrow is one a convention plugin adds):", "")
        val drawn = mods.filter { m -> m.label != ":" || main.any { it.source == m.id || it.target == m.id } } // an empty root project is left out
        out += mermaid(drawn.map { it.id }, main.map { Arrow(it.source, it.target, if (it.attrs.str("via") != null) "-.->" else "-->") }, g)
    }
}

private fun room(g: Graph, out: MutableList<String>) {
    val dbs = g.byKind("room_database")
    if (dbs.isEmpty()) return
    out += listOf("## Room", "")
    for (db in dbs) {
        val fq = db.id.substringAfter("::")
        val schemas = g.byKind("room_schema").filter { it.attrs.str("db") == fq }.mapNotNull { it.attrs.int("version") }.sorted()
        fun related(kind: String) = list(g.outEdges(db.id).filter { it.kind == kind }.map { g.label(it.target) }.sorted())
        out += listOf("### ${db.label} (version ${db.attrs.int("version")})", "",
            "- File: `${location(db.file, db.line)}`",
            "- Schema files: ${schemas.joinToString(", ").ifEmpty { "none" }}",
            "- Entities: ${related("contains_entity")}",
            "- DAOs: ${related("contains_dao")}",
            "", "| Step | Kind | Tested by |", "|---|---|---|")
        val migs = g.byKind("room_migration").filter { it.attrs.str("db") == fq }
            .sortedWith(compareBy({ it.attrs.int("from_version") }, { it.attrs.int("to_version") }))
        for (m in migs) {
            val tests = g.inEdges(m.id).filter { it.kind == "tests" }.map { g.label(it.source) }.sorted()
            out.add("| ${m.attrs.int("from_version")} -> ${m.attrs.int("to_version")} | ${m.attrs.str("style")} | " +
                "${tests.joinToString(", ").ifEmpty { "**none**" }} |")
        }
        out.add("")
    }
}

private fun navigation(g: Graph, out: MutableList<String>) {
    val dests = g.byKind("nav_destination").filter { it.attrs.bool("registered") }.sortedBy { it.label }
    if (dests.isEmpty()) return
    out += listOf("## Navigation", "", "| Destination | API | Shows | Reached from |", "|---|---|---|---|")
    for (d in dests) {
        val shows = g.outEdges(d.id).filter { it.kind == "shows" }.map { g.label(it.target) }.sorted()
        val from = g.inEdges(d.id).filter { it.kind == "navigates_to" || it.kind == "starts_at" }.map { g.label(it.source) }.toSortedSet()
        out.add("| `${d.label}` | ${d.attrs.str("api")} | ${list(shows)} | ${list(from)} |")
    }
    out.add("")
    // Screen to screen: a navigate call in a screen's code starts at the destinations that show that screen.
    val shownBy = g.edgesOf("shows").groupBy({ it.target }, { it.source })
    val arrows = ArrayList<Arrow>()
    for (e in g.edges) {
        if ((e.kind != "navigates_to" && e.kind != "starts_at") || g.nodes[e.target]?.kind != "nav_destination") continue
        val from = if (g.nodes[e.source]?.kind == "nav_destination") listOf(e.source) else shownBy[e.source] ?: listOf(e.source)
        for (s in from) arrows.add(Arrow(s, e.target, if (e.kind == "starts_at") "==>" else "-->"))
    }
    if (arrows.isNotEmpty()) {
        out += listOf("Screen flow (a thick arrow is a start destination; a red box is a route no destination registers):", "")
        out += mermaid(dests.map { it.id }, arrows, g)
    }
}

private fun di(g: Graph, out: MutableList<String>) {
    val providers = g.byKind("hilt_provider").sortedBy { it.label }
    val definitions = g.byKind("koin_definition").sortedBy { it.label }
    val vms = g.byKind("viewmodel").sortedBy { it.label }
    if (providers.isEmpty() && definitions.isEmpty() && vms.isEmpty()) return
    out += listOf("## Dependency injection", "")
    if (vms.isNotEmpty()) {
        out += listOf("| ViewModel | Injects | Used by |", "|---|---|---|")
        for (v in vms) {
            val deps = g.outEdges(v.id).filter { it.kind == "injects" }.map { g.label(it.target) }.sorted()
            val users = g.inEdges(v.id).filter { it.kind == "uses_viewmodel" }.map { g.label(it.source) }.toSortedSet()
            out.add("| ${v.label} | ${list(deps)} | ${list(users)} |")
        }
        out.add("")
    }
    if (providers.isNotEmpty()) {
        out += listOf("| Hilt binding | Provides | Module |", "|---|---|---|")
        for (pn in providers) {
            val a = pn.attrs
            val q = a.str("qualifier")?.let { " @$it" } ?: ""
            out.add("| ${pn.label} (${a.str("style")}) | `${a.str("returns")}`$q | ${(a.str("hilt_module") ?: "-").substringAfterLast('.')} |")
        }
        out.add("")
    }
    if (definitions.isNotEmpty()) {
        out += listOf("| Koin definition | Provides | Where |", "|---|---|---|")
        for (d in definitions) {
            out.add("| ${d.label} | ${list(d.attrs.strings("provides").map { "`${it.substringAfterLast('.')}`" })} | `${location(d.file, d.line)}` |")
        }
        out.add("")
    }
}

private fun permissions(g: Graph, out: MutableList<String>) {
    val edges = g.edgesOf("uses_permission").filter { !it.attrs.bool("removed") }
    if (edges.isEmpty()) return
    out += listOf("## Permissions", "", "| Permission | Declared in |", "|---|---|")
    for ((perm, es) in edges.groupBy { it.target.substringAfter("::") }.toSortedMap()) {
        val where = es.map { e ->
            if (e.attrs.bool("merged")) "merged manifest of ${g.label(e.source)} (${e.attrs.strings("variants").joinToString(", ")})" +
                (e.attrs.strings("added_by").takeIf { it.isNotEmpty() }?.let { ", added by ${it.joinToString(", ")}" } ?: "")
            else "`${e.file}`" + (e.attrs.str("max_sdk")?.let { " (up to SDK $it)" } ?: "")
        }.toSortedSet()
        out.add("| `$perm` | ${md(where.joinToString("; "))} |")
    }
    out.add("")
}

private class Arrow(val from: String, val to: String, val style: String)

/**
 * A Mermaid flowchart of [nodes] (graph ids) and [arrows] between them; nodes an arrow reaches that are
 * not in [nodes] are drawn too, with ones that have no destination in red. Too large a graph is left out.
 */
private fun mermaid(nodes: List<String>, arrows: List<Arrow>, g: Graph): List<String> {
    val ids = LinkedHashMap<String, String>()
    for (n in nodes + arrows.flatMap { listOf(it.from, it.to) }) ids.getOrPut(n) { "n${ids.size}" }
    if (ids.size > MAX_DIAGRAM_NODES) return listOf("(${ids.size} nodes: too many to draw)", "")
    val lines = arrayListOf("```mermaid", "flowchart LR")
    for ((id, short) in ids) lines.add("  $short[\"${g.label(id).replace("\"", "#quot;")}\"]")
    for (a in arrows.distinctBy { Triple(it.from, it.to, it.style) }) lines.add("  ${ids[a.from]} ${a.style} ${ids[a.to]}")
    val missing = ids.filter { (id, _) -> g.nodes[id]?.let { it.kind == "nav_destination" && !it.attrs.bool("registered") } == true }.values
    if (missing.isNotEmpty()) {
        lines.add("  classDef missing stroke:#d33,stroke-width:2px")
        lines.add("  class ${missing.joinToString(",")} missing")
    }
    lines += listOf("```", "")
    return lines
}
